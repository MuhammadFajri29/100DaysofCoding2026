public class Days10 {
    public static void main(String[] args) {

        //Setiap tipe data numerik di Java memiliki batas minimal (minimum) dan batas maksimal (maximum).

        // Batas minimum dan maksimum tipe data byte 8 bit
        System.out.println("Byte minimum: " + Byte.MIN_VALUE);
        System.out.println("Byte maksimum: " + Byte.MAX_VALUE);

        // Batas minimum dan maksimum tipe data short 16 bit
        System.out.println("Short minimum:" + Short.MIN_VALUE);
        System.out.println("Short maksimum:" + Short.MAX_VALUE);

        // Batas minimum dan maksimum tipe data int 32 bit
        System.out.println("Int minimum: " + Integer.MIN_VALUE);
        System.out.println("Int maksimum: " + Integer.MAX_VALUE);

        // Batas minimum dan maksimum tipe data double 64 bit
        System.out.println("Double minimum: " + Double.MIN_VALUE);
        System.out.println("Double maksimum: " + Double.MAX_VALUE);
    }
}
